/**
 * Builds css/drupal-layer.css: the CSS of Drupal core, Classy and the modules
 * that the frontend loads, wrapped in the cascade layer "legacy".
 *
 * CSS outside of any layer always wins over layered CSS, and CSS in a lower
 * layer always loses, whatever the specificity. To keep the cascade exactly as
 * it was before the layers, this CSS is in the same layer as the legacy bundle
 * (palm.css) and comes before it, in the order Drupal loaded the files (module
 * group by weight, then the theme group). Within one layer, specificity and
 * order decide as before; only the layer components wins over all of it.
 *
 * The original files are removed via libraries-override in palm.info.yml.
 * Relative url()s are rewritten to absolute paths.
 *
 * Run `make drupal-layer` after updating Drupal core, Classy or one of the
 * modules. Keep the list in sync with libraries-override in palm.info.yml;
 * add new module CSS that shows up on the frontend.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const themeDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const webRoot = resolve(themeDir, '../../..');

const stable = 'themes/contrib/stable/css';
const classy = [
  'action-links', 'breadcrumb', 'button', 'collapse-processed', 'container-inline', 'details',
  'exposed-filters', 'field', 'form', 'icons', 'inline-form', 'item-list', 'link', 'links', 'menu',
  'more-link', 'pager', 'tabledrag', 'tableselect', 'tablesort', 'tabs', 'textarea', 'ui-dialog',
  'messages', 'progress', 'user',
];

// Same order as Drupal loaded them: module CSS by weight, then the theme CSS.
const files = [
  // weight -10: system/base, system/status.report
  `${stable}/system/components/align.module.css`,
  `${stable}/system/components/clearfix.module.css`,
  `${stable}/system/components/container-inline.module.css`,
  `${stable}/system/components/hidden.module.css`,
  `${stable}/system/components/js.module.css`,
  'core/modules/system/css/components/system-status-counter.css',
  'core/modules/system/css/components/system-status-report-counters.css',
  'core/modules/system/css/components/system-status-report-general-info.css',
  // weight 0: core/drupal.ajax, item-list, progress, textarea-resize, captions, oEmbed, user, views
  `${stable}/core/components/ajax-progress.module.css`,
  'core/misc/components/item-list.module.css',
  `${stable}/core/components/progress.module.css`,
  `${stable}/system/components/resize.module.css`,
  `${stable}/filter/filter.caption.css`,
  `${stable}/media/filter.caption.css`,
  `${stable}/media/oembed.formatter.css`,
  `${stable}/user/user.module.css`,
  `${stable}/views/views.module.css`,
  // weight 100: EU Cookie Compliance
  'modules/contrib/eu_cookie_compliance/css/eu_cookie_compliance.bare.css',
  // weight 190: system/admin
  `${stable}/system/system.admin.css`,
  // weight 200: NodeShop, CAPTCHA
  'modules/contrib/nodeshop/css/nodeshop.css',
  'modules/contrib/captcha/css/captcha.css',
  // theme group: normalize, Classy
  `${stable}/core/assets/vendor/normalize-css/normalize.css`,
  `${stable}/core/normalize-fixes.css`,
  ...classy.map((name) => `themes/contrib/classy/css/components/${name}.css`),
];

const absoluteUrls = (css, file) => css.replace(/url\(\s*(['"]?)([^'")]+)\1\s*\)/g, (match, quote, url) => {
  if (/^(data:|\/|https?:|#)/.test(url)) {
    return match;
  }
  return `url(${quote}${posix.normalize(`/${posix.dirname(file)}/${url}`)}${quote})`;
});

const parts = files.map((file) => `/* ${file} */\n${absoluteUrls(readFileSync(join(webRoot, file), 'utf8'), file).trim()}`);

writeFileSync(join(themeDir, 'css/drupal-layer.css'), [
  '/* Generated by scripts/build-drupal-layer.mjs, do not edit. */',
  '@layer legacy {',
  ...parts,
  '}',
  '',
].join('\n'));

console.log(`css/drupal-layer.css: ${files.length} files`);
