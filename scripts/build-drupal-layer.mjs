/**
 * Builds css/drupal-layer.css: the base CSS of core, Classy, EU Cookie
 * Compliance and CAPTCHA wrapped in the cascade layer "drupal".
 *
 * CSS outside of any layer always wins over layered CSS. The legacy bundle
 * (palm.css) lives in the layer "legacy", so the original files are removed via
 * libraries-override in palm.info.yml and loaded from this copy instead, in the
 * same order as before. Relative url()s are rewritten to absolute paths.
 *
 * Run `npm run drupal-layer` after updating Drupal core, Classy, EU Cookie
 * Compliance or CAPTCHA. Keep the list in sync with libraries-override in
 * palm.info.yml.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const themeDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const webRoot = resolve(themeDir, '../../..');

const classy = [
  'action-links', 'breadcrumb', 'button', 'collapse-processed', 'container-inline', 'details',
  'exposed-filters', 'field', 'form', 'icons', 'inline-form', 'item-list', 'link', 'links', 'menu',
  'more-link', 'pager', 'tabledrag', 'tableselect', 'tablesort', 'tabs', 'textarea', 'ui-dialog',
  'messages',
];

// Same order as Drupal loaded them: module CSS first, then the base theme CSS.
const files = [
  'modules/contrib/eu_cookie_compliance/css/eu_cookie_compliance.bare.css',
  'modules/contrib/captcha/css/captcha.css',
  'themes/contrib/stable/css/core/assets/vendor/normalize-css/normalize.css',
  'themes/contrib/stable/css/core/normalize-fixes.css',
  ...classy.map((name) => `themes/contrib/classy/css/components/${name}.css`),
];

const absoluteUrls = (css, file) => css.replace(/url\(\s*(['"]?)([^'")]+)\1\s*\)/g, (match, quote, url) => {
  if (/^(data:|\/|https?:|#)/.test(url)) {
    return match;
  }
  return `url(${quote}${posix.normalize(`/${posix.dirname(file)}/${url}`)}${quote})`;
});

const parts = files.map((file) => `/* ${file} */\n${absoluteUrls(readFileSync(join(webRoot, file), 'utf8'), file).trim()}`);

writeFileSync(join(themeDir, 'css/drupal-layer.css'), [
  '/* Generated by scripts/build-drupal-layer.mjs, do not edit. */',
  '@layer drupal {',
  ...parts,
  '}',
  '',
].join('\n'));

console.log(`css/drupal-layer.css: ${files.length} files`);
